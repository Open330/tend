#!/usr/bin/env node
// Generates the web dashboard's design tokens from the one source both Tend
// for Mac and the dashboard follow: apps/shared/Design/tokens.json.
//
//   node scripts/design-tokens.mjs           # rewrite tokens.css and the Swift tokens
//   node scripts/design-tokens.mjs --check   # exit 1 when either is stale
//
// The output is committed, so tendd serves it as a plain file and nobody
// who builds tend runs this. crates/tend/tests-js/design-tokens.test.mjs
// fails when the CSS is stale or when TendTheme.swift / BrandMark.swift
// drift from tokens.json.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const TOKENS_PATH = join(ROOT, "apps/shared/Design/tokens.json");
export const CSS_PATH = join(ROOT, "crates/tend/src/dashboard/web/tokens.css");
/// Compiled into Tend for Mac and the iOS app (both build apps/shared/Sources).
export const SWIFT_PATH = join(ROOT, "apps/shared/Sources/TendDesignTokens.swift");

const camel = (name) => name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

/// `#RRGGBB` → `0xRRGGBB, alpha 1`; `rgba(r, g, b, a)` → the hex and its alpha.
function swiftColor(value) {
  const hex = /^#([0-9a-f]{6})$/i.exec(value);
  if (hex) return { rgb: `0x${hex[1].toUpperCase()}`, alpha: "1" };
  const rgba = /^rgba\((\d+),\s*(\d+),\s*(\d+),\s*([0-9.]+)\)$/.exec(value);
  if (!rgba) throw new Error(`unsupported colour ${value}`);
  const byte = (n) => Number(n).toString(16).padStart(2, "0").toUpperCase();
  return { rgb: `0x${byte(rgba[1])}${byte(rgba[2])}${byte(rgba[3])}`, alpha: rgba[4] };
}

function number(px) {
  const value = String(px).replace(/px$/, "");
  return value.includes(".") ? value : `${value}`;
}

export function renderSwift(tokens) {
  const lines = [
    "// Generated by scripts/design-tokens.mjs from apps/shared/Design/tokens.json.",
    "// Do not edit: change tokens.json and run `node scripts/design-tokens.mjs`.",
    "//",
    "// Platform-neutral values (no SwiftUI): Tend for Mac's TendTheme and the",
    "// iOS app's Theme turn them into colours and metrics.",
    "",
    "/// One colour in both appearances: sRGB hex and opacity.",
    "struct TendTokenColor: Sendable, Equatable {",
    "    let light: UInt32",
    "    let lightAlpha: Double",
    "    let dark: UInt32",
    "    let darkAlpha: Double",
    "}",
    "",
    "enum TendDesignTokens {",
  ];
  for (const [name, value] of Object.entries(tokens.color)) {
    const light = swiftColor(value.light);
    const dark = swiftColor(value.dark);
    lines.push(`    static let ${camel(name)} = TendTokenColor(light: ${light.rgb}, lightAlpha: ${light.alpha}, dark: ${dark.rgb}, darkAlpha: ${dark.alpha})`);
  }
  lines.push("", "    /// The four-room mark's lit rooms, and the ink and dimming of the rest.", "    enum Brand {");
  for (const room of ["waiting", "error", "done"]) lines.push(`        static let ${room}: UInt32 = ${swiftColor(tokens.brand[room]).rgb}`);
  lines.push(`        static let ink = TendTokenColor(light: ${swiftColor(tokens.brand.ink.light).rgb}, lightAlpha: 1, dark: ${swiftColor(tokens.brand.ink.dark).rgb}, darkAlpha: 1)`);
  lines.push(`        static let dimLight: Double = ${tokens.brand.dim.light}`, `        static let dimDark: Double = ${tokens.brand.dim.dark}`, "    }");
  lines.push("", "    /// Host and agent identity discs, top to bottom (index: FNV-1a of the alias, modulo the count).", "    static let hostGradients: [(top: UInt32, bottom: UInt32)] = [");
  for (const [top, bottom] of tokens.host.gradients) lines.push(`        (${swiftColor(top).rgb}, ${swiftColor(bottom).rgb}),`);
  lines.push("    ]", "", "    /// Type sizes in points.", "    enum Size {");
  for (const [name, value] of Object.entries(tokens.size)) lines.push(`        static let ${camel(name)}: Double = ${number(value)}`);
  lines.push("    }", "", "    /// Metrics in points.", "    enum Metric {");
  for (const [name, value] of Object.entries(tokens.metric)) lines.push(`        static let ${camel(name)}: Double = ${number(value)}`);
  lines.push("    }", "}", "");
  return lines.join("\n");
}

export function renderCss(tokens) {
  const light = [];
  const dark = [];
  const common = [];
  for (const [name, value] of Object.entries(tokens.color)) {
    light.push(`  --${name}: ${value.light};`);
    dark.push(`  --${name}: ${value.dark};`);
  }
  for (const [name, color] of Object.entries(tokens.state)) {
    if (name.startsWith("$")) continue;
    common.push(`  --state-${name}: var(--${color});`);
  }
  for (const room of ["waiting", "error", "done"]) common.push(`  --brand-${room}: ${tokens.brand[room]};`);
  light.push(`  --brand-ink: ${tokens.brand.ink.light};`, `  --brand-dim: ${tokens.brand.dim.light};`);
  dark.push(`  --brand-ink: ${tokens.brand.ink.dark};`, `  --brand-dim: ${tokens.brand.dim.dark};`);
  tokens.host.gradients.forEach(([top, bottom], index) => {
    common.push(`  --host-${index}: linear-gradient(${top}, ${bottom});`);
  });
  for (const [name, value] of Object.entries(tokens.font)) common.push(`  --font-${name}: ${value};`);
  for (const [name, value] of Object.entries(tokens.size)) common.push(`  --size-${name}: ${value};`);
  for (const [name, value] of Object.entries(tokens.metric)) common.push(`  --${name}: ${value};`);
  return [
    "/* Generated by scripts/design-tokens.mjs from apps/shared/Design/tokens.json. Do not edit. */",
    ":root {",
    "  color-scheme: light dark;",
    ...light,
    ...common,
    "}",
    "@media (prefers-color-scheme: dark) {",
    "  :root {",
    ...dark.map((line) => `  ${line}`),
    "  }",
    "}",
    "",
  ].join("\n");
}

export function readTokens() {
  return JSON.parse(readFileSync(TOKENS_PATH, "utf8"));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const tokens = readTokens();
  const outputs = [[CSS_PATH, renderCss(tokens)], [SWIFT_PATH, renderSwift(tokens)]];
  if (process.argv.includes("--check")) {
    const stale = outputs.filter(([path, text]) => readFileSync(path, "utf8") !== text);
    if (stale.length) {
      console.error(`stale: ${stale.map(([path]) => path).join(", ")}; run node scripts/design-tokens.mjs`);
      process.exit(1);
    }
  } else {
    for (const [path, text] of outputs) writeFileSync(path, text);
  }
}
