#!/usr/bin/env node
// Generates the web dashboard's design tokens from the one source both Tend
// for Mac and the dashboard follow: apps/shared/Design/tokens.json.
//
//   node scripts/design-tokens.mjs           # rewrite web/tokens.css
//   node scripts/design-tokens.mjs --check   # exit 1 when it is stale
//
// The output is committed, so tendd serves it as a plain file and nobody
// who builds tend runs this. crates/tend/tests-js/design-tokens.test.mjs
// fails when the CSS is stale or when TendTheme.swift / BrandMark.swift
// drift from tokens.json.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const TOKENS_PATH = join(ROOT, "apps/shared/Design/tokens.json");
export const CSS_PATH = join(ROOT, "crates/tend/src/dashboard/web/tokens.css");

export function renderCss(tokens) {
  const light = [];
  const dark = [];
  const common = [];
  for (const [name, value] of Object.entries(tokens.color)) {
    light.push(`  --${name}: ${value.light};`);
    dark.push(`  --${name}: ${value.dark};`);
  }
  for (const [name, color] of Object.entries(tokens.state)) {
    if (name.startsWith("$")) continue;
    common.push(`  --state-${name}: var(--${color});`);
  }
  for (const room of ["waiting", "error", "done"]) common.push(`  --brand-${room}: ${tokens.brand[room]};`);
  light.push(`  --brand-ink: ${tokens.brand.ink.light};`, `  --brand-dim: ${tokens.brand.dim.light};`);
  dark.push(`  --brand-ink: ${tokens.brand.ink.dark};`, `  --brand-dim: ${tokens.brand.dim.dark};`);
  tokens.host.gradients.forEach(([top, bottom], index) => {
    common.push(`  --host-${index}: linear-gradient(${top}, ${bottom});`);
  });
  for (const [name, value] of Object.entries(tokens.font)) common.push(`  --font-${name}: ${value};`);
  for (const [name, value] of Object.entries(tokens.size)) common.push(`  --size-${name}: ${value};`);
  for (const [name, value] of Object.entries(tokens.metric)) common.push(`  --${name}: ${value};`);
  return [
    "/* Generated by scripts/design-tokens.mjs from apps/shared/Design/tokens.json. Do not edit. */",
    ":root {",
    "  color-scheme: light dark;",
    ...light,
    ...common,
    "}",
    "@media (prefers-color-scheme: dark) {",
    "  :root {",
    ...dark.map((line) => `  ${line}`),
    "  }",
    "}",
    "",
  ].join("\n");
}

export function readTokens() {
  return JSON.parse(readFileSync(TOKENS_PATH, "utf8"));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const css = renderCss(readTokens());
  if (process.argv.includes("--check")) {
    const current = readFileSync(CSS_PATH, "utf8");
    if (current !== css) {
      console.error("tokens.css is stale: run node scripts/design-tokens.mjs");
      process.exit(1);
    }
  } else {
    writeFileSync(CSS_PATH, css);
  }
}
