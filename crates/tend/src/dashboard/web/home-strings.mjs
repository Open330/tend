/// A model text: a plain string, or `{ key, ... }` for words the page owns.
export function textOf(strings, value) {
  if (value == null) return "";
  if (typeof value === "string") return value;
  // The daemon's board nests texts ({key: "owner_says", text: {...}}).
  const args = {};
  for (const [name, arg] of Object.entries(value)) args[name] = name === "key" ? arg : typeof arg === "object" ? textOf(strings, arg) : arg;
  const word = strings[value.key];
  return typeof word === "function" ? word(args) : word || "";
}

export function languageOf(languages = []) {
  const first = String(languages[0] || "en").toLowerCase();
  return first.startsWith("ko") ? "ko" : "en";
}

export function stringsFor(lang) {
  return lang === "ko" ? KO : EN;
}

/// "4 min. ago" / "4분 전", as the Mac's abbreviated relative dates read.
export function relativeTime(iso, now = Date.now(), lang = "en") {
  const then = Date.parse(iso || "");
  if (!Number.isFinite(then)) return "";
  const seconds = Math.round((then - now) / 1000);
  const format = new Intl.RelativeTimeFormat(lang, { numeric: "always", style: "short" });
  const abs = Math.abs(seconds);
  if (abs < 60) return format.format(Math.min(0, seconds), "second");
  if (abs < 3600) return format.format(Math.round(seconds / 60), "minute");
  if (abs < 86400) return format.format(Math.round(seconds / 3600), "hour");
  return format.format(Math.round(seconds / 86400), "day");
}
